#!/bin/sh
# formula.sh VERSION SHA256SUMS — print the Homebrew formula for a release.
#
# VERSION is the tag without the leading "v" (1.4.0). SHA256SUMS is the file
# the release workflow publishes beside the binaries. The formula installs the
# prebuilt static binary for the platform; nothing is compiled on install.
#
# The release workflow runs this and pushes the result to the tap repository
# (maborak/homebrew-tap, Formula/mabo-ctl.rb), so `brew install
# maborak/tap/mabo-ctl` follows every release.
set -eu

version=${1:?usage: formula.sh VERSION SHA256SUMS}
sums=${2:?usage: formula.sh VERSION SHA256SUMS}
version=${version#v}
# The version is interpolated into Ruby: refuse anything but a plain version, so
# a tag such as v1#{system("id")} cannot become code every `brew install` runs.
case $version in
'' | *[!0-9A-Za-z.+-]* | [!0-9]*)
	echo "formula.sh: refusing version \"$version\"; want digits, letters, . + -" >&2
	exit 1
	;;
esac
base="https://github.com/maborak/mabo-ctl/releases/download/v${version}"

sum() {
	s=$(awk -v f="mabo-ctl-$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")
	case $s in
	[0-9a-f]*) [ ${#s} -eq 64 ] && { printf '%s' "$s"; return; } ;;
	esac
	echo "formula.sh: no SHA-256 for mabo-ctl-$1 in $sums" >&2
	exit 1
}

darwin_arm64=$(sum darwin-arm64)
darwin_amd64=$(sum darwin-amd64)
linux_arm64=$(sum linux-arm64)
linux_amd64=$(sum linux-amd64)

cat <<RUBY
# typed: false
# frozen_string_literal: true

# Generated by packaging/homebrew/formula.sh in maborak/mabo-ctl. Do not edit.
class MaboCtl < Formula
  desc "Per-repo local dev process supervisor: start, stop, health-check and tail services"
  homepage "https://github.com/maborak/mabo-ctl"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/mabo-ctl-darwin-arm64"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/mabo-ctl-darwin-amd64"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/mabo-ctl-linux-arm64"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/mabo-ctl-linux-amd64"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install Dir["mabo-ctl-*"].first => "mabo-ctl"
    generate_completions_from_executable(bin/"mabo-ctl", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mabo-ctl --version")
  end
end
RUBY
